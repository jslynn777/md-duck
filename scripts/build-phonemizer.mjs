#!/usr/bin/env node
// Build only the pinned public source, in an isolated container without any app profile.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { promises as fs } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'src/main/kokoro-runtime-phonemizer')
const manifest = JSON.parse(await fs.readFile(join(target, 'SOURCE.json'), 'utf8'))
const archiveArgument = process.argv.indexOf('--archive')
const suppliedArchive = archiveArgument >= 0 ? resolve(process.argv[archiveArgument + 1] ?? '') : null
const verifyOnly = process.argv.includes('--verify')
const scratch = await fs.mkdtemp(join(tmpdir(), 'md-duck-phonemizer-source-'))
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
const shellQuote = (value) => `'${String(value).replaceAll("'", "'\\''")}'`
function run(command, args) {
  const result = spawnSync(command, args, { cwd: root, stdio: 'inherit', timeout: 900_000 })
  if (result.error) throw result.error
  assert.equal(result.status, 0, `${command} failed`)
}
try {
  const archive = join(scratch, manifest.sourceArchive.file)
  if (suppliedArchive) await fs.copyFile(suppliedArchive, archive)
  else {
    const response = await fetch(manifest.sourceArchive.url, { signal: AbortSignal.timeout(180_000) })
    assert(response.ok, 'Could not retrieve the pinned engine source')
    await fs.writeFile(archive, Buffer.from(await response.arrayBuffer()))
  }
  const sourceBytes = await fs.readFile(archive)
  assert.equal(sourceBytes.length, manifest.sourceArchive.bytes)
  assert.equal(sha256(sourceBytes), manifest.sourceArchive.sha256, 'Pinned source archive hash differs')
  const source = join(scratch, 'source')
  await fs.mkdir(source)
  run('tar', ['-xzf', archive, '--strip-components=1', '-C', source])
  const recipe = join(source, 'emscripten/build.sh')
  let script = await fs.readFile(recipe, 'utf8')
  for (const from of [
    '-DCMAKE_C_COMPILER=clang -DCMAKE_CXX_COMPILER=clang++',
    '--export-es6 --quiet',
    "    cat '../readme-header.md' '../emscripten/README.md' > '../README.md'"
  ]) assert(script.includes(from), `Upstream recipe changed: ${from}`)
  script = script.replace('-DCMAKE_C_COMPILER=clang -DCMAKE_CXX_COMPILER=clang++', '-DCMAKE_C_COMPILER=cc -DCMAKE_CXX_COMPILER=c++')
    .replace('--export-es6 --quiet', '--quiet')
    .replace("    cat '../readme-header.md' '../emscripten/README.md' > '../README.md'", '')
  await fs.writeFile(recipe, script)
  const language = manifest.languageOptions
  const build = `set -e; EMSDK=/emsdk emscripten/build.sh native preload -dict ${shellQuote(language.dictionaryRegex)} -lang ${shellQuote(language.languageRegex)} -name ${shellQuote(language.name)} -desc ${shellQuote(language.description)}; EMSDK=/emsdk emscripten/build.sh wasm ephone`
  run('docker', ['run', '--rm', '--platform', manifest.emscripten.platform, '-v', `${source}:/src`, '-w', '/src', manifest.emscripten.container, 'bash', '-lc', build])
  for (const file of ['ephone.js', 'lang/en_all.js']) {
    const bytes = await fs.readFile(join(source, 'build/dist', file))
    const expected = manifest.outputs.find((entry) => entry.file === file)
    assert(expected, 'Missing output identity')
    assert.equal(bytes.length, expected.bytes, `Generated size differs: ${file}`)
    assert.equal(sha256(bytes), expected.sha256, `Generated byte hash differs: ${file}`)
    if (!verifyOnly) {
      await fs.mkdir(dirname(join(target, file)), { recursive: true })
      await fs.writeFile(join(target, file), bytes)
    }
  }
  console.log(JSON.stringify({ status: 'passed', sourceCommit: manifest.sourceCommit, compiler: manifest.emscripten.container, outputs: 'Match recorded engine and English data bytes', verifyOnly }, null, 2))
} finally { await fs.rm(scratch, { recursive: true, force: true }) }
