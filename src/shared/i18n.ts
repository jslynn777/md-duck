export function blockConvention(lang: UiLang) {
  if (lang === 'zh') {
    return `请在发布稿 article.md 和中文稿 article.zh.md 里使用相同的块标记。
标记写成 HTML 注释，单独放在段落、标题、列表项、图片、表格或代码块之前，前后各空一行：
<!-- block:短名称 -->
修改已有段落时保留原标记。只有新段落才新增标记。不要删除、改名，也不要把标记写进代码块。`
  }
  return `Use the same block markers in article.md and article.zh.md.
Write each marker as an HTML comment on its own line, with a blank line before and after, placed before the paragraph, heading, list item, image, table, or code block:
<!-- block:short-name -->
Keep the marker when you edit an existing paragraph. Add a marker only for a new paragraph. Do not delete or rename markers, and do not put them inside code blocks.`
}

